DO $$
BEGIN
  CREATE TYPE "UserRole" AS ENUM ('TESTER', 'DEVELOPER', 'ADMIN');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE "RankTier" AS ENUM ('ALPHA_SEEDER', 'CORE_VALIDATOR', 'APEX_ARCHITECT');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

ALTER TABLE "User"
  ADD COLUMN IF NOT EXISTS "role" "UserRole" NOT NULL DEFAULT 'TESTER',
  ADD COLUMN IF NOT EXISTS "username" TEXT NOT NULL DEFAULT 'SeedEnv Member',
  ADD COLUMN IF NOT EXISTS "avatarUrl" TEXT,
  ADD COLUMN IF NOT EXISTS "bio" TEXT,
  ADD COLUMN IF NOT EXISTS "portfolioUrl" TEXT,
  ADD COLUMN IF NOT EXISTS "companyName" TEXT,
  ADD COLUMN IF NOT EXISTS "productUrl" TEXT,
  ADD COLUMN IF NOT EXISTS "walletBalanceCents" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "xpPoints" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "rankTier" "RankTier" NOT NULL DEFAULT 'ALPHA_SEEDER',
  ADD COLUMN IF NOT EXISTS "streakDays" INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS "lastActiveDate" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS "stripeCustomerId" TEXT,
  ADD COLUMN IF NOT EXISTS "stripeConnectAccountId" TEXT;

CREATE INDEX IF NOT EXISTS "User_role_idx" ON "User"("role");
CREATE INDEX IF NOT EXISTS "User_rankTier_xpPoints_idx" ON "User"("rankTier", "xpPoints");